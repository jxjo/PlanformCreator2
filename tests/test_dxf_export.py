import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace

import ezdxf

from planformcreator2.model.wing_exports import Dxf_Wing_Artist


class TestDxfTitle(unittest.TestCase):

    def test_title_uses_current_wing_name(self):
        wing = SimpleNamespace(
            name="Original wing",
            parm_path=Path("Original wing.pc2"),
            planform=SimpleNamespace(chord_root=230.0),
        )
        artist = Dxf_Wing_Artist(wing)
        wing.name = "Example"
        artist.plot_title()

        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "Renamed wing_wing.dxf"
            artist.save(str(path))
            texts = [
                entity.dxf.text
                for entity in ezdxf.readfile(path).modelspace().query("TEXT")
            ]

        self.assertEqual(texts[0], "Example")
        self.assertNotIn("Original wing", texts)
        self.assertEqual(texts[1], "Generated by PlanformCreator2")


if __name__ == "__main__":
    unittest.main()
